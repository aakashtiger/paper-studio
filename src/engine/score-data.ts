/**
 * `score-data.js` is the score **as the page reads it**: the resolved plan plus
 * the pose libraries, generated from `score.json` by `npm run embed`.
 *
 * It is generated, so it can be regenerated — and that is the check worth
 * having. The renderer paints from this file, not from `score.json`, so a score
 * edited without re-embedding, or a `score-data.js` hand-edited to say something
 * the brief does not, would be a film painted from data that is not the contract.
 * One function produces the text, `embed` writes it and `gate:7` compares it.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { FilmScoreSchema, resolveFilm } from "./treatment.js";

export function scoreDataText(root: string, scorePath: string): string {
  const score = FilmScoreSchema.parse(JSON.parse(readFileSync(resolve(root, scorePath), "utf8")));
  const { plan, errors } = resolveFilm(score, resolve(root, `styles/${score.style}`), root);
  if (errors.length > 0) {
    throw new Error(`the score does not resolve: ${errors[0]?.message ?? "unknown error"}`);
  }
  const poses: Record<string, unknown> = {};
  for (const entry of plan.cast) {
    poses[entry.character] = JSON.parse(readFileSync(resolve(root, entry.poses), "utf8"));
  }
  return (
    `/* Generated by npm run embed from ${score.id}/score.json. Do not edit. */\n` +
    `window.SCORE = ${JSON.stringify(plan, null, 2)};\n` +
    `window.POSES = ${JSON.stringify(poses, null, 2)};\n`
  );
}

export function scoreDataPath(root: string, film: string): string {
  return resolve(root, "films", film, "score-data.js");
}
