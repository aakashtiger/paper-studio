/**
 * `score-data.js` is generated from `score.json`, and the renderer paints from
 * it — so "the page's data is the score" is a claim the repo can check. It
 * shipped stale once (five `quiet` reasons and the cue → event bindings were
 * missing), which is why the gate regenerates it instead of trusting it.
 */
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import test from "node:test";
import { scoreDataPath, scoreDataText } from "../src/engine/score-data.js";

const root = process.cwd();
const SCORE_PATH = "films/understudy/score.json";

test("the checked-in score data is what the score generates today", () => {
  const onDisk = readFileSync(scoreDataPath(root, "understudy"), "utf8");
  assert.equal(
    onDisk,
    scoreDataText(root, SCORE_PATH),
    "films/understudy/score-data.js is stale — run `npm run embed -- films/understudy/score.json`",
  );
});

test("the page's data carries what the score says, not a subset of it", () => {
  const text = scoreDataText(root, SCORE_PATH);
  // The two fields whose absence made the file stale in the first place: an
  // unscored event's reason, and a cue bound to its picture event.
  assert.match(text, /"quiet":/);
  assert.match(text, /"event":/);
  assert.match(text, /^\/\* Generated by npm run embed from understudy\/score\.json\. Do not edit\. \*\//);
});

test("the page reads the score's own numbers", () => {
  const text = scoreDataText(root, SCORE_PATH);
  const score = JSON.parse(readFileSync(resolve(root, SCORE_PATH), "utf8")) as {
    duration: number;
    shots: { recipe: string }[];
    audio?: { sfx?: { cues?: { id: string; at?: number; event?: unknown }[] } };
  };
  // `window.SCORE = { ... };` — the painter reads `duration` and `shots[].recipe`.
  const head = "window.SCORE = ";
  const start = text.indexOf(head) + head.length;
  const page = JSON.parse(text.slice(start, text.indexOf(";\nwindow.POSES"))) as {
    duration: number;
    shots: { id: string; recipe: string }[];
    cues: { id: string; at?: number; event?: unknown }[];
  };
  assert.equal(page.duration, score.duration);
  assert.deepEqual(
    page.shots.map((shot) => shot.recipe),
    score.shots.map((shot) => shot.recipe),
  );
  // The plan gives each shot the id the rest of the score refers to.
  assert.equal(new Set(page.shots.map((shot) => shot.id)).size, page.shots.length);
  // A cue that names its event must have had its time derived, not dropped.
  for (const cue of score.audio?.sfx?.cues ?? []) {
    if (!cue.event) continue;
    const resolved = page.cues.find((entry) => entry.id === cue.id);
    assert.equal(typeof resolved?.at, "number", `${cue.id} lost the time its event resolves to`);
  }
});

test("scoreDataPath is the film's page data", () => {
  assert.equal(scoreDataPath(root, "understudy"), resolve(root, "films", "understudy", "score-data.js"));
});
