import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { FilmScoreSchema, resolveFilm } from "../src/engine/treatment.js";

const args = process.argv.slice(2);
const file = args.find((arg) => !arg.startsWith("--"));
if (!file) {
  console.error("usage: npm run embed -- <score.json>");
  process.exit(2);
}

const root = process.cwd();
const score = FilmScoreSchema.parse(JSON.parse(readFileSync(resolve(root, file), "utf8")));
const { plan, errors } = resolveFilm(score, resolve(root, `styles/${score.style}`), root);
if (errors.length > 0) {
  for (const error of errors) console.error(`error: ${error.message}`);
  process.exit(1);
}

const poses: Record<string, unknown> = {};
for (const entry of plan.cast) {
  poses[entry.character] = JSON.parse(readFileSync(resolve(root, entry.poses), "utf8"));
}

const out = resolve(root, "films", score.id, "score-data.js");
writeFileSync(
  out,
  `/* Generated by npm run embed from ${score.id}/score.json. Do not edit. */\nwindow.SCORE = ${JSON.stringify(plan, null, 2)};\nwindow.POSES = ${JSON.stringify(poses, null, 2)};\n`,
  "utf8",
);
console.log(`embed: films/${score.id}/score-data.js`);
